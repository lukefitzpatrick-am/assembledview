/**
 * S17 against a real Postgres: migration 0123 (twice), the one writer
 * (`recordFindings`), the owner it resolves, the open-item unique key, the
 * daily sweep and the screen's read and close.
 *
 * Skips unless DATA_QUALITY_TEST_DATABASE_URL names a LOCAL database whose
 * name ends in `_dq_test`. It rebuilds that database's public schema.
 */

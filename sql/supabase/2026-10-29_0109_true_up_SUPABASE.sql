-- 0109_true_up: guarded run file for Luke.
-- Supabase project slpdibnxtpdlttbbczvg. Luke runs this by hand in the SQL Editor.
-- Same DDL as db/migrations/0109_true_up.sql (the repo copy, AUTHOR ONLY).
--
-- What it does
--   Creates public.true_up_runs, public.true_up_actions and
--   public.true_up_invoice_links (all empty, RLS on), adds
--   client_finance_owners.billing_timing (null = same month), widens
--   billing_revisions_mode_check to allow 'true_up' and 'true_up_restore',
--   and writes the marker 0109_true_up. Touches no existing rows.
--   The true-up report runs without it. Fixes, invoice links, billing timing
--   and the monthly run refuse until it exists.
--
-- Needs 0105 (client_finance_owners) and 0106 (billing_revisions) first.
--
-- Run order
--   1. Run the BEFORE block. Check every expected value.
--   2. Run the DO block. It refuses (nothing done) if the marker or a table
--      already exists, and rolls back if any AFTER check inside fails.
--   3. Run the AFTER block. Check every expected value.

-- ===================== BEFORE (read only) =====================
SELECT to_regclass('public.true_up_runs') AS true_up_runs,                      -- expect NULL
       to_regclass('public.true_up_actions') AS true_up_actions,                -- expect NULL
       to_regclass('public.true_up_invoice_links') AS true_up_invoice_links;    -- expect NULL
SELECT key FROM public.migration_markers
 WHERE key IN ('0105_client_finance_owners', '0106_billing_revisions', '0109_true_up')
 ORDER BY key;                                       -- expect 0105 and 0106 only (2 rows)
SELECT pg_get_constraintdef(oid) FROM pg_constraint
 WHERE conrelid = 'public.billing_revisions'::regclass
   AND conname = 'billing_revisions_mode_check';     -- expect the 5 modes, no true_up
SELECT count(*) AS billing_timing_cols FROM information_schema.columns
 WHERE table_schema = 'public' AND table_name = 'client_finance_owners'
   AND column_name = 'billing_timing';               -- expect 0

-- ===================== CHANGE (one DO block) =====================
DO $$
DECLARE
  n_tables   integer;
  n_rls      integer;
  n_marker   integer;
  n_col      integer;
  mode_def   text;
  n_rows     bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM public.migration_markers WHERE key = '0109_true_up') THEN
    RAISE EXCEPTION 'marker 0109_true_up already exists - nothing done';
  END IF;
  IF to_regclass('public.true_up_runs') IS NOT NULL
     OR to_regclass('public.true_up_actions') IS NOT NULL
     OR to_regclass('public.true_up_invoice_links') IS NOT NULL THEN
    RAISE EXCEPTION 'a true_up table already exists - nothing done';
  END IF;
  IF to_regclass('public.billing_revisions') IS NULL THEN
    RAISE EXCEPTION '0109 needs 0106 (billing_revisions) first';
  END IF;
  IF to_regclass('public.client_finance_owners') IS NULL THEN
    RAISE EXCEPTION '0109 needs 0105 (client_finance_owners) first';
  END IF;

  CREATE TABLE IF NOT EXISTS public.true_up_runs (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           timestamptz NOT NULL DEFAULT now(),
    as_of_month          date NOT NULL,
    from_month           date NOT NULL,
    source               text NOT NULL,
    created_by           bigint NULL,
    created_by_name      text NULL,
    xero_synced_at       timestamptz NULL,
    provisional_invoices integer NOT NULL DEFAULT 0,
    mbas_needing_action  integer NOT NULL DEFAULT 0,
    totals               jsonb NOT NULL,
    rows                 jsonb NOT NULL,
    emailed_at           timestamptz NULL,
    CONSTRAINT true_up_runs_source_check CHECK (source IN ('cron', 'manual')),
    CONSTRAINT true_up_runs_months_check
      CHECK (as_of_month = date_trunc('month', as_of_month)::date
             AND from_month = date_trunc('month', from_month)::date
             AND from_month <= as_of_month)
  );
  CREATE INDEX IF NOT EXISTS idx_true_up_runs_as_of
    ON public.true_up_runs (as_of_month DESC, created_at DESC);

  CREATE TABLE IF NOT EXISTS public.true_up_actions (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          timestamptz NOT NULL DEFAULT now(),
    run_id              bigint NULL REFERENCES public.true_up_runs(id) ON DELETE SET NULL,
    mba_number          text NOT NULL,
    component           text NOT NULL,
    action              text NOT NULL,
    strategy            text NULL,
    months              text[] NOT NULL DEFAULT '{}',
    as_of_month         date NOT NULL,
    gap_cents           bigint NOT NULL,
    amount_cents        bigint NOT NULL DEFAULT 0,
    billing_revision_id bigint NULL REFERENCES public.billing_revisions(id) ON DELETE SET NULL,
    reason_code         text NULL,
    note                text NULL,
    xero_invoice_id     text NULL,
    status              text NOT NULL DEFAULT 'applied',
    created_by          bigint NOT NULL,
    created_by_name     text NULL,
    undone_at           timestamptz NULL,
    undone_by           bigint NULL,
    preview_hash        text NULL,
    CONSTRAINT true_up_actions_component_check
      CHECK (component IN ('fee', 'adserving', 'production', 'media')),
    CONSTRAINT true_up_actions_action_check
      CHECK (action IN ('schedule', 'explained', 'one_off', 'credit_note')),
    CONSTRAINT true_up_actions_strategy_check
      CHECK (strategy IS NULL OR strategy IN ('spread', 'carry')),
    CONSTRAINT true_up_actions_reason_check
      CHECK (reason_code IS NULL OR reason_code IN ('timing', 'prebill', 'client_agreed', 'schedule_incomplete', 'other')),
    CONSTRAINT true_up_actions_status_check CHECK (status IN ('applied', 'undone')),
    CONSTRAINT true_up_actions_mba_check CHECK (length(btrim(mba_number)) > 0)
  );
  CREATE INDEX IF NOT EXISTS idx_true_up_actions_mba
    ON public.true_up_actions (lower(mba_number), component, status);
  CREATE INDEX IF NOT EXISTS idx_true_up_actions_revision
    ON public.true_up_actions (billing_revision_id) WHERE billing_revision_id IS NOT NULL;

  CREATE TABLE IF NOT EXISTS public.true_up_invoice_links (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        timestamptz NOT NULL DEFAULT now(),
    xero_invoice_id   text NOT NULL,
    mba_number        text NOT NULL,
    billing_month     date NULL,
    note              text NULL,
    created_by        bigint NOT NULL,
    created_by_name   text NULL,
    CONSTRAINT true_up_invoice_links_mba_check CHECK (length(btrim(mba_number)) > 0),
    CONSTRAINT true_up_invoice_links_month_check
      CHECK (billing_month IS NULL OR billing_month = date_trunc('month', billing_month)::date)
  );
  CREATE UNIQUE INDEX IF NOT EXISTS uq_true_up_invoice_links_invoice
    ON public.true_up_invoice_links (xero_invoice_id);

  ALTER TABLE public.client_finance_owners
    ADD COLUMN IF NOT EXISTS billing_timing text NULL;
  ALTER TABLE public.client_finance_owners
    DROP CONSTRAINT IF EXISTS client_finance_owners_billing_timing_check;
  ALTER TABLE public.client_finance_owners
    ADD CONSTRAINT client_finance_owners_billing_timing_check
    CHECK (billing_timing IS NULL OR billing_timing IN ('same_month', 'month_ahead', 'in_arrears'));

  ALTER TABLE public.billing_revisions DROP CONSTRAINT IF EXISTS billing_revisions_mode_check;
  ALTER TABLE public.billing_revisions ADD CONSTRAINT billing_revisions_mode_check
    CHECK (mode IN ('pull_month', 'bill_remainder', 'bill_amount', 'underspend', 'restore', 'true_up', 'true_up_restore'));

  COMMENT ON TABLE public.true_up_runs IS
    'Monthly true-up runs (cron on the 2nd or manual): the computed report per run.';
  COMMENT ON TABLE public.true_up_actions IS
    'True-up ledger: schedule fixes (with their billing revision), explained gaps, one-offs to raise and credit-note flags.';
  COMMENT ON TABLE public.true_up_invoice_links IS
    'Hand links from a Xero invoice to an MBA (and optional billing month) for the true-up.';

  ALTER TABLE public.true_up_runs ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.true_up_actions ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.true_up_invoice_links ENABLE ROW LEVEL SECURITY;

  INSERT INTO public.migration_markers (key, note)
  VALUES ('0109_true_up', 'true_up_runs, true_up_actions, true_up_invoice_links, client_finance_owners.billing_timing, billing_revisions modes true_up and true_up_restore.');
  -- AFTER checks inside the block. Any failure rolls the whole block back.
  SELECT count(*) INTO n_tables FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname IN ('true_up_runs', 'true_up_actions', 'true_up_invoice_links');
  IF n_tables <> 3 THEN
    RAISE EXCEPTION 'expected 3 true_up tables, found %', n_tables;
  END IF;
  SELECT count(*) INTO n_rls FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname IN ('true_up_runs', 'true_up_actions', 'true_up_invoice_links')
     AND c.relrowsecurity;
  IF n_rls <> 3 THEN
    RAISE EXCEPTION 'expected RLS on all 3 true_up tables, found %', n_rls;
  END IF;
  SELECT (SELECT count(*) FROM public.true_up_runs) + (SELECT count(*) FROM public.true_up_actions)
       + (SELECT count(*) FROM public.true_up_invoice_links) INTO n_rows;
  IF n_rows <> 0 THEN
    RAISE EXCEPTION 'expected empty true_up tables, found % rows', n_rows;
  END IF;
  SELECT count(*) INTO n_col FROM information_schema.columns
   WHERE table_schema = 'public' AND table_name = 'client_finance_owners' AND column_name = 'billing_timing';
  IF n_col <> 1 THEN
    RAISE EXCEPTION 'expected client_finance_owners.billing_timing';
  END IF;
  SELECT pg_get_constraintdef(oid) INTO mode_def FROM pg_constraint
   WHERE conrelid = 'public.billing_revisions'::regclass AND conname = 'billing_revisions_mode_check';
  IF mode_def IS NULL OR position('true_up_restore' IN mode_def) = 0 THEN
    RAISE EXCEPTION 'billing_revisions_mode_check does not allow true_up_restore: %', mode_def;
  END IF;
  SELECT count(*) INTO n_marker FROM public.migration_markers WHERE key = '0109_true_up';
  IF n_marker <> 1 THEN
    RAISE EXCEPTION 'expected 1 marker row, found %', n_marker;
  END IF;

  RAISE NOTICE '0109_true_up applied: 3 tables (empty, RLS on), billing_timing column, revision modes, marker written.';
END
$$;

-- ===================== AFTER (read only) =====================
SELECT to_regclass('public.true_up_runs') AS true_up_runs,                      -- expect true_up_runs
       to_regclass('public.true_up_actions') AS true_up_actions,                -- expect true_up_actions
       to_regclass('public.true_up_invoice_links') AS true_up_invoice_links;    -- expect true_up_invoice_links
SELECT relname, relrowsecurity FROM pg_class
 WHERE relname IN ('true_up_runs', 'true_up_actions', 'true_up_invoice_links')
 ORDER BY relname;                                   -- expect 3 rows, all true
SELECT pg_get_constraintdef(oid) FROM pg_constraint
 WHERE conrelid = 'public.billing_revisions'::regclass
   AND conname = 'billing_revisions_mode_check';     -- expect 7 modes incl. true_up, true_up_restore
SELECT count(*) AS billing_timing_cols FROM information_schema.columns
 WHERE table_schema = 'public' AND table_name = 'client_finance_owners'
   AND column_name = 'billing_timing';               -- expect 1
SELECT key FROM public.migration_markers WHERE key = '0109_true_up';   -- expect 1 row

/**
 * Generate db/schema TypeScript from the applied SQL migrations.
 * Usage: node scripts/migration/_gen-drizzle-schema.mjs
 */
import fs from "fs"
import path from "path"

const rawSql = [
  fs.readFileSync("db/migrations/0001_ported_tables.sql", "utf8"),
  fs.readFileSync("db/migrations/0002_plan_core.sql", "utf8"),
  fs.readFileSync("db/migrations/0004_clients_missing_columns.sql", "utf8"),
].join("\n")

// Strip line comments before parsing so `)` inside comments cannot truncate table bodies.
const sql = rawSql
  .split("\n")
  .map((l) => l.replace(/--.*$/, ""))
  .join("\n")

function toCamel(name) {
  return name.replace(/_([a-z0-9])/gi, (_, c) => c.toUpperCase())
}

function dbColName(raw) {
  // Unquoted PG identifiers fold to lowercase.
  return raw.toLowerCase()
}

const indexRe =
  /create (unique )?index (?:if not exists )?(\w+) on (\w+) \(([^)]+)\);/gi
/** @type {Record<string, {unique:boolean,name:string,cols:string[]}[]>} */
const indexesByTable = {}
for (const m of sql.matchAll(indexRe)) {
  const [, uniq, name, table, cols] = m
  if (!indexesByTable[table]) indexesByTable[table] = []
  indexesByTable[table].push({
    unique: Boolean(uniq),
    name,
    cols: cols.split(",").map((c) => dbColName(c.trim())),
  })
}

function mapType(pgType, colName) {
  const n = `'${colName}'`
  switch (pgType) {
    case "bigint":
      return `bigint(${n}, { mode: "number" })`
    case "int":
      return `integer(${n})`
    case "text":
      return `text(${n})`
    case "boolean":
      return `boolean(${n})`
    case "numeric":
      return `numeric(${n})`
    case "date":
      return `date(${n})`
    case "timestamptz":
      return `timestamp(${n}, { withTimezone: true, mode: "string" })`
    case "jsonb":
      return `jsonb(${n})`
    case "line_channel":
      return `lineChannelEnum(${n})`
    case "schedule_component":
      return `scheduleComponentEnum(${n})`
    case "schedule_basis":
      return `scheduleBasisEnum(${n})`
    case "schedule_source":
      return `scheduleSourceEnum(${n})`
    default:
      throw new Error(`Unknown type ${pgType} for ${colName}`)
  }
}

const tableRe = /create table if not exists (\w+) \(([\s\S]*?)\);/gi
/** @type {Array<{name:string, columns:string[], extras:string[], imports:Set<string>}>} */
const tables = []

for (const m of sql.matchAll(tableRe)) {
  const tableName = m[1]
  const body = m[2]
  const rawLines = body
    .split("\n")
    .map((l) => l.replace(/--.*$/, "").trim())
    .filter(Boolean)
    .map((l) => l.replace(/,$/, ""))

  /** @type {string[]} */
  const columns = []
  /** @type {string[]} */
  const tableUniques = []
  const imports = new Set([
    "bigint",
    "boolean",
    "date",
    "integer",
    "jsonb",
    "numeric",
    "pgTable",
    "text",
    "timestamp",
  ])

  for (const line of rawLines) {
    if (/^unique\s*\(/i.test(line)) {
      const colsMatch = line.match(/unique\s*\(([^)]+)\)/i)
      if (colsMatch) {
        tableUniques.push(
          colsMatch[1].split(",").map((c) => dbColName(c.trim())),
        )
      }
      continue
    }

    const colRaw = line.split(/\s+/)[0]
    const col = dbColName(colRaw)
    const rest = line.slice(colRaw.length).trim()
    const pgType = rest.split(/\s+/)[0]
    const isIdentityPk = /generated by default as identity primary key/i.test(
      rest,
    )
    const notNull = /\bnot null\b/i.test(rest)
    const defaultNow = /default now\(\)/i.test(rest)
    const defaultComputed = /default 'computed'/i.test(rest)
    const defaultManual = /default 'manual'/i.test(rest)
    const colUnique = /\bunique\b/i.test(rest) && !isIdentityPk
    const refs = rest.match(
      /references (\w+)\((\w+)\)(?: on delete (\w+(?:\s+\w+)?))?/i,
    )

    let expr
    if (isIdentityPk) {
      expr = `bigint("${col}", { mode: "number" }).generatedByDefaultAsIdentity().primaryKey()`
    } else {
      expr = mapType(pgType, col)
      if (refs) {
        const refTable = refs[1]
        const refCol = dbColName(refs[2])
        const onDelete = refs[3]?.toLowerCase().replace(/\s+/g, " ")
        const del = onDelete ? `, { onDelete: "${onDelete}" }` : ""
        expr += `.references(() => ${toCamel(refTable)}.${toCamel(refCol)}${del})`
      }
      if (notNull) expr += `.notNull()`
      if (defaultNow) expr += `.defaultNow()`
      if (defaultComputed) expr += `.default("computed")`
      if (defaultManual) expr += `.default("manual")`
      if (colUnique) expr += `.unique()`
    }

    columns.push(`  ${toCamel(col)}: ${expr},`)
  }

  /** @type {string[]} */
  const extras = []
  const idxs = indexesByTable[tableName] || []
  if (idxs.length || tableUniques.length) {
    imports.add("index")
    imports.add("uniqueIndex")
    imports.add("unique")
  }

  for (const u of tableUniques) {
    const fields = u.map((c) => `table.${toCamel(c)}`).join(", ")
    extras.push(`    unique().on(${fields}),`)
  }
  for (const idx of idxs) {
    const fields = idx.cols.map((c) => `table.${toCamel(c)}`).join(", ")
    if (idx.unique) {
      extras.push(`    uniqueIndex("${idx.name}").on(${fields}),`)
    } else {
      extras.push(`    index("${idx.name}").on(${fields}),`)
    }
  }

  tables.push({ name: tableName, columns, extras, imports })
}

// Merge `ALTER TABLE … ADD COLUMN IF NOT EXISTS` from later migrations (e.g. 0004).
const alterAddRe =
  /alter table (\w+) add column if not exists (\w+) ([a-z0-9_]+)(?:\s+[^;]*)?;/gi
for (const m of sql.matchAll(alterAddRe)) {
  const tableName = m[1]
  const col = dbColName(m[2])
  const pgType = m[3].toLowerCase()
  const table = tables.find((t) => t.name === tableName)
  if (!table) {
    throw new Error(`ALTER ADD COLUMN on unknown table ${tableName}.${col}`)
  }
  const already = table.columns.some((c) =>
    c.trimStart().startsWith(`${toCamel(col)}:`),
  )
  if (already) continue
  const expr = mapType(pgType, col)
  table.columns.push(`  ${toCamel(col)}: ${expr},`)
}


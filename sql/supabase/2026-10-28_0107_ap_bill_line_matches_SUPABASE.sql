--   existing rows. Once the marker exists, Finance > Publishers > Fixed cost
--   margin > Bill lines shows "Match" on unmatched and ambiguous bill lines,
--   and the matcher applies saved matches before any automatic rule (MAR-4).
--
-- Run order
--   1. Run the BEFORE block. Check every expected value.
--   2. Run the DO block. It refuses (nothing done) if the table or the marker
--      already exists, and rolls back if any AFTER check inside fails.
--   3. Run the AFTER block. Check every expected value.
--
-- Measured 2026-10-28 (read-only SELECTs)
--   to_regclass('public.ap_bill_line_matches') = NULL
--   latest marker = 0106_billing_revisions (2026-10-26 23:45 UTC)

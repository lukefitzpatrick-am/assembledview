/**
 * B48 (S16 A): setFeatureSwitch on a real Postgres. A refused change writes
 * nothing (no row, no event); an allowed one writes both.
 *
 * Skips unless FEATURES_TEST_DATABASE_URL names a LOCAL database whose name
 * ends in _features_test. The suite creates the three tables it needs and
 * drops them after.
 */
import assert from "node:assert/strict"
import { after, before, describe, test } from "node:test"

import postgres from "postgres"

import { classifyTestDatabaseUrl } from "@/lib/testing/testDatabaseGuard"

const RAW_URL = process.env.FEATURES_TEST_DATABASE_URL?.trim() ?? ""
const URL_ = (() => {
  if (!RAW_URL || !classifyTestDatabaseUrl(RAW_URL).ok) return null
  try {
    return new URL(RAW_URL).pathname.endsWith("_features_test") ? RAW_URL : null
  } catch {
    return null
  }
})()
const skip = URL_ ? false : "set FEATURES_TEST_DATABASE_URL to a local database named *_features_test"

const ACTOR = { id: 7, name: "Luke" }

describe("setFeatureSwitch", { skip }, () => {
  let sql: ReturnType<typeof postgres>
  let server: typeof import("@/lib/features/server")

  before(async () => {
    process.env.DATABASE_URL = URL_!
    sql = postgres(URL_!, { max: 1, onnotice: () => {} })
    await sql.unsafe(`
      DROP TABLE IF EXISTS feature_switches, feature_switch_events, migration_markers;
      CREATE TABLE feature_switches (key text primary key, enabled boolean not null, updated_at timestamptz not null default now(),
        updated_by bigint, updated_by_name text, note text);
      CREATE TABLE feature_switch_events (id bigint generated by default as identity primary key, created_at timestamptz not null default now(),
        key text not null, from_enabled boolean, to_enabled boolean not null, changed_by bigint, changed_by_name text, note text);
      CREATE TABLE migration_markers (key text primary key, applied_at timestamptz not null default now(), note text);
      INSERT INTO migration_markers (key) VALUES ('0111_feature_switches');
    `)
    server = await import("@/lib/features/server")
  })

  after(async () => {
    await sql?.unsafe(`DROP TABLE IF EXISTS feature_switches, feature_switch_events, migration_markers`)
    await sql?.end()
    const { closeDb } = await import("@/db")
    await closeDb()
  })

  const events = async () => (await sql`SELECT key, from_enabled, to_enabled FROM feature_switch_events ORDER BY id`).map((r) => ({ ...r }))

  test("on is refused while a requirement is off; nothing is written", async () => {
    const out = await server.setFeatureSwitch({ key: "true_up_actions", enabled: true, note: null, actor: ACTOR, env: {} })
    assert.deepEqual(out, { ok: false, status: 409, code: "SWITCH_DEPENDENCY", message: "Turn on True-up report first: this switch needs it." })
    assert.equal((await sql`SELECT count(*)::int AS n FROM feature_switches`)[0].n, 0)
    assert.deepEqual(await events(), [])
  })

  test("a requirement from its env var counts (no row yet)", async () => {
    const out = await server.setFeatureSwitch({ key: "true_up_cron", enabled: true, note: null, actor: ACTOR, env: { TRUE_UP: "on" } })
    assert.equal(out.ok, true)
  })

  test("on, then off of the requirement is refused while the dependant is on, then allowed after it", async () => {
    assert.equal((await server.setFeatureSwitch({ key: "true_up", enabled: true, note: null, actor: ACTOR, env: {} })).ok, true)
    const refused = await server.setFeatureSwitch({ key: "true_up", enabled: false, note: "try", actor: ACTOR, env: {} })
    assert.deepEqual(refused, { ok: false, status: 409, code: "SWITCH_DEPENDENCY", message: "Turn off Monthly true-up run first: it needs this switch." })
    assert.equal((await sql`SELECT enabled FROM feature_switches WHERE key = 'true_up'`)[0].enabled, true)
    assert.equal((await server.setFeatureSwitch({ key: "true_up_cron", enabled: false, note: null, actor: ACTOR, env: {} })).ok, true)
    assert.equal((await server.setFeatureSwitch({ key: "true_up", enabled: false, note: null, actor: ACTOR, env: {} })).ok, true)
    assert.deepEqual(await events(), [
      { key: "true_up_cron", from_enabled: false, to_enabled: true },
      { key: "true_up", from_enabled: false, to_enabled: true },
      { key: "true_up_cron", from_enabled: true, to_enabled: false },
      { key: "true_up", from_enabled: true, to_enabled: false },
    ])
  })

  test("a switch whose migration marker is missing can't be turned on; once the marker exists it can", async () => {
    assert.equal((await server.setFeatureSwitch({ key: "codex_v2", enabled: true, note: null, actor: ACTOR, env: {} })).ok, true)
    const refused = await server.setFeatureSwitch({ key: "codex_saved_views", enabled: true, note: null, actor: ACTOR, env: {} })
    assert.deepEqual(refused, { ok: false, status: 409, code: "SWITCH_DEPENDENCY", message: "Run migration 0117_codex_saved_views first: this switch needs it." })
    assert.equal((await sql`SELECT count(*)::int AS n FROM feature_switches WHERE key = 'codex_saved_views'`)[0].n, 0)
    await sql`INSERT INTO migration_markers (key) VALUES ('0117_codex_saved_views')`
    const { setMarkerReaderForTests } = await import("@/lib/db/markers")
    setMarkerReaderForTests(null) // forget the cached "missing" answer, as the recheck window would
    assert.equal((await server.setFeatureSwitch({ key: "codex_saved_views", enabled: true, note: null, actor: ACTOR, env: {} })).ok, true)
    assert.equal(await server.isFeatureOn("codex_saved_views", {}), true)
  })

  test("on since: the latest event that turned it on, not a later save at the same value; a row with no such event uses its updated time", async () => {
    await sql`DELETE FROM feature_switches`
    await sql`DELETE FROM feature_switch_events`
    await sql`INSERT INTO feature_switches (key, enabled, updated_at) VALUES ('web_search', true, '2026-11-02T00:00:00Z'), ('creative_performance', true, '2026-11-03T00:00:00Z'), ('auto_reports', false, '2026-11-03T00:00:00Z')`
    await sql`INSERT INTO feature_switch_events (created_at, key, from_enabled, to_enabled) VALUES
      ('2026-10-20T00:00:00Z', 'web_search', false, true),
      ('2026-10-25T00:00:00Z', 'web_search', true, false),
      ('2026-10-30T00:00:00Z', 'web_search', null, true),
      ('2026-11-02T00:00:00Z', 'web_search', true, true),
      ('2026-11-03T00:00:00Z', 'creative_performance', true, true),
      ('2026-10-01T00:00:00Z', 'auto_reports', false, true)`
    server.invalidateFeatureSwitches()
    const { states } = await server.readFeatureStates({})
    const on = (key: string) => states.find((s) => s.key === key)!.onSince
    assert.equal(Date.parse(on("web_search")!), Date.parse("2026-10-30T00:00:00Z"))
    assert.equal(Date.parse(on("creative_performance")!), Date.parse("2026-11-03T00:00:00Z"), "Save current values: the row's time")
    assert.equal(on("auto_reports"), null, "off now")
    assert.equal(on("true_up"), null, "no row")
  })
})

/**
 * Codex projects store (S1, B38) against a real Postgres with migration 0118
 * applied. Skips unless CODEX_PROJECTS_TEST_DATABASE_URL names a LOCAL
 * database whose name ends in `_codex_test` (the test drops and rebuilds its
 * public schema). It never reads .env.local and never reaches production.
 *
 *   createdb -h 127.0.0.1 -p 5432 av_codex_test
 *   CODEX_PROJECTS_TEST_DATABASE_URL=postgres://postgres@127.0.0.1:5432/av_codex_test npm run test:codex-projects
 *
 * Builds a minimal replica of tasks (live columns and checks as of 13 Nov
 * 2026), then runs db/migrations/0118_codex_s1_projects.sql itself, so the
 * migration, the sync trigger and the raw SQL in projectsRepo.ts are all
 * exercised.
 */
import assert from "node:assert/strict"
import fs from "node:fs"
import path from "node:path"
import { after, before, describe, it } from "node:test"

import postgres from "postgres"
import { drizzle } from "drizzle-orm/postgres-js"

import * as schema from "@/db/schema"
import type { Db } from "@/db"
import { classifyTestDatabaseUrl } from "../../testing/testDatabaseGuard"
import {
  addProjectMembers,
  completeProjectTask,
  createProject,
  createSection,
  deleteSection,
  getProject,
  listProjects,
  listSections,
  moveTaskToSection,
  removeProjectMember,
  reorderSections,
  resetProjectsMarkerCacheForTests,
  updateProject,
  updateSection,
  ProjectsUnavailableError,
} from "../projectsRepo.js"

const RAW_URL = process.env.CODEX_PROJECTS_TEST_DATABASE_URL?.trim() ?? ""

function usableUrl(url: string): boolean {
  if (!url) return false
  if (!classifyTestDatabaseUrl(url).ok) return false
  try {
    return new URL(url).pathname.replace(/^\//, "").endsWith("_codex_test")
  } catch {
    return false
  }
}

const skip = usableUrl(RAW_URL)
  ? false
  : "set CODEX_PROJECTS_TEST_DATABASE_URL to a local database named *_codex_test"

const BASE_SQL = `
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
SET TimeZone = 'UTC';
CREATE TABLE public.migration_markers (key text primary key, applied_at timestamptz not null default now(), note text);
CREATE TABLE public.clients (id bigint primary key);
CREATE TABLE public.client_notes (id bigint generated by default as identity primary key);
CREATE TABLE public.task_templates (id bigint generated by default as identity primary key, name text, description text, created_at timestamptz not null default now());
CREATE TABLE public.tasks (
  id bigint generated by default as identity primary key, client_id bigint, mba_number text, title text not null, description text,
  status text not null default 'todo' CONSTRAINT tasks_status_check CHECK (status in ('backlog','todo','in_progress','waiting','done')),
  priority text default 'normal', due_date timestamptz, recurring_rule text, template_id bigint references public.task_templates(id) on delete set null,
  client_visible boolean, created_at timestamptz not null default now(), updated_at timestamptz, assignee_email text, assignee_name text,
  created_by_email text, source text not null default 'manual', source_note_id bigint references public.client_notes(id) on delete set null,
  category text, deleted_at timestamptz, auto_created boolean not null default false, ava_auto_key text, estimated_minutes integer,
  parent_task_id bigint references public.tasks(id) on delete set null, help_requested_by_email text, help_prior_status text,
  CONSTRAINT tasks_priority_check CHECK (priority IS NULL OR priority IN ('low','normal','high')),
  CONSTRAINT tasks_source_check CHECK (source IN ('manual','ava','template','recurring') OR source LIKE 'profile:%'));
CREATE TABLE public.task_comments (id bigint generated by default as identity primary key, task_id bigint references public.tasks(id) on delete cascade,
  body text, created_at timestamptz not null default now(), author_email text, author_name text, author_kind text not null default 'user');
CREATE TABLE public.codex_activity (id bigint generated always as identity primary key, entity_type text not null, entity_id bigint not null,
  actor_email text, actor_kind text not null default 'user', action text not null, before jsonb, after jsonb, created_at timestamptz not null default now());
INSERT INTO public.clients (id) VALUES (42);
INSERT INTO public.tasks (title, due_date, status) VALUES ('old due', '2026-08-14', 'todo');
`

const OWNER = "owner@assembledmedia.com.au"
const MEMBER = "member@assembledmedia.com.au"
const OTHER = "other@assembledmedia.com.au"

describe("codex projects store on Postgres (0118 applied)", { skip }, () => {
  let client: ReturnType<typeof postgres>
  let database: Db

  async function newTask(title: string, status = "todo"): Promise<number> {
    const [row] = await client`INSERT INTO public.tasks (title, status) VALUES (${title}, ${status}) RETURNING id`
    return Number(row.id)
  }
  async function taskRow(id: number) {
    const [row] = await client`SELECT id, status, project_id, section_id, sort_order, completed_at, due_on, deleted_at FROM public.tasks WHERE id = ${id}`
    return row
  }

  before(async () => {
    client = postgres(RAW_URL, { max: 2, onnotice: () => {} })
    await client.unsafe(BASE_SQL)
    resetProjectsMarkerCacheForTests()
    database = drizzle(client, { schema }) as unknown as Db
  })

  after(async () => {
    resetProjectsMarkerCacheForTests()
    await client?.end({ timeout: 5 })
  })

  it("before 0118: every call is ProjectsUnavailableError", async () => {
    await assert.rejects(listProjects(OWNER, {}, database), ProjectsUnavailableError)
    await assert.rejects(createProject(OWNER, {
      name: "x", kind: "ops", client_id: null, mba_number: null, owner_email: null, is_private: false,
      start_on: null, due_on: null, members: [], sections: undefined,
    }, database), ProjectsUnavailableError)
  })

  it("applies the 0118 migration, filling due_on once", async () => {
    const file = path.join(process.cwd(), "db/migrations/0118_codex_s1_projects.sql")
    await client.unsafe(fs.readFileSync(file, "utf8"))
    await client.unsafe(fs.readFileSync(file, "utf8"))
    const [m] = await client`SELECT count(*)::int AS n FROM public.migration_markers WHERE key = '0118_codex_s1_projects'`
    assert.equal(m.n, 1)
    const [t] = await client`SELECT due_on::text AS due_on FROM public.tasks WHERE title = 'old due'`
    assert.equal(t.due_on, "2026-08-14")
    resetProjectsMarkerCacheForTests()
  })

  let projectId = 0
  let privateId = 0
  const sectionIds: Record<string, number> = {}

  it("creates a project with default sections (To do, In progress, Done) and an activity row", async () => {
    const r = await createProject(OWNER, {
      name: "Sinch", kind: "campaign", client_id: 42, mba_number: "sinch001", owner_email: null, is_private: false,
      start_on: "2026-12-07", due_on: null, members: [], sections: undefined,
    }, database)
    assert.ok(r.ok)
    projectId = r.project.id
    assert.equal(r.project.owner_email, OWNER, "owner defaults to the creator")
    assert.deepEqual(r.sections.map((s) => [s.name, s.status_category, s.sort_order]), [
      ["To do", "todo", 0], ["In progress", "in_progress", 1], ["Done", "done", 2],
    ])
    for (const s of r.sections) sectionIds[s.name] = s.id
    const [a] = await client`SELECT count(*)::int AS n FROM public.codex_activity WHERE entity_type = 'codex_project' AND entity_id = ${projectId}`
    assert.equal(a.n, 1)
  })

  it("refuses an unknown client and a second live project on the same MBA", async () => {
    const base = { kind: "campaign" as const, owner_email: null, is_private: false, start_on: null, due_on: null, members: [], sections: undefined }
    const unknown = await createProject(OWNER, { ...base, name: "X", client_id: 7, mba_number: null }, database)
    assert.equal(!unknown.ok && unknown.reason, "unknown_client")
    const dup = await createProject(OWNER, { ...base, name: "Y", client_id: null, mba_number: "sinch001" }, database)
    assert.equal(!dup.ok && dup.reason, "mba_taken")
  })

  it("private projects: listed and readable only by owner, creator and members", async () => {
    const r = await createProject(OWNER, {
      name: "Private", kind: "internal", client_id: null, mba_number: null, owner_email: null, is_private: true,
      start_on: null, due_on: null, members: [MEMBER], sections: [{ name: "Backlog", status_category: "todo" }],
    }, database)
    assert.ok(r.ok)
    privateId = r.project.id
    assert.deepEqual(r.sections.map((s) => s.name), ["Backlog", "Done"], "Done appended")
    const names = async (who: string) => (await listProjects(who, {}, database)).map((p) => p.name)
    assert.deepEqual(await names(OWNER), ["Private", "Sinch"])
    assert.deepEqual(await names(MEMBER.toUpperCase()), ["Private", "Sinch"])
    assert.deepEqual(await names(OTHER), ["Sinch"])
    const hidden = await getProject(privateId, OTHER, database)
    assert.equal(!hidden.ok && hidden.reason, "not_found")
    const hiddenSections = await listSections(privateId, OTHER, database)
    assert.equal(!hiddenSections.ok && hiddenSections.reason, "not_found")
    const hiddenRename = await updateProject(privateId, OTHER, { name: "Mine" }, database)
    assert.equal(!hiddenRename.ok && hiddenRename.reason, "not_found")
  })

  it("members work in a private project; only owner or creator changes access", async () => {
    const rename = await updateProject(privateId, MEMBER, { name: "Private 2", status: "on_hold" }, database)
    assert.ok(rename.ok && rename.project.name === "Private 2" && rename.project.status === "on_hold")
    const flip = await updateProject(privateId, MEMBER, { is_private: false }, database)
    assert.equal(!flip.ok && flip.reason, "not_owner")
    const add = await addProjectMembers(privateId, MEMBER, [OTHER], database)
    assert.equal(!add.ok && add.reason, "not_owner")
    const ownerAdd = await addProjectMembers(privateId, OWNER, [OTHER, MEMBER], database)
    assert.ok(ownerAdd.ok)
    assert.deepEqual(ownerAdd.project.members, [MEMBER, OTHER])
    assert.ok((await getProject(privateId, OTHER, database)).ok)
    const removed = await removeProjectMember(privateId, OWNER, OTHER, database)
    assert.ok(removed.ok && !removed.project.members.includes(OTHER))
    assert.equal((await getProject(privateId, OTHER, database)).ok, false)
    const closed = await listProjects(OWNER, { status: "on_hold" }, database)
    assert.deepEqual(closed.map((p) => p.id), [privateId])
  })

  it("sections: create last, rename, recategorise, keep a done section, reorder", async () => {
    const waiting = await createSection(projectId, OTHER, { name: "Awaiting client", status_category: "waiting", collapsed_default: false }, database)
    assert.ok(waiting.ok && waiting.section.sort_order === 3)
    sectionIds["Awaiting client"] = waiting.ok ? waiting.section.id : 0
    const lastDone = await updateSection(projectId, sectionIds["Done"], OWNER, { status_category: "todo" }, database)
    assert.equal(!lastDone.ok && lastDone.reason, "last_done_section")
    const lastDoneDelete = await deleteSection(projectId, sectionIds["Done"], OWNER, database)
    assert.equal(!lastDoneDelete.ok && lastDoneDelete.reason, "last_done_section")
    const renamed = await updateSection(projectId, sectionIds["In progress"], OWNER, { name: "Doing", collapsed_default: true }, database)
    assert.ok(renamed.ok && renamed.section.name === "Doing" && renamed.section.collapsed_default)
    const wrongProject = await updateSection(privateId, sectionIds["Doing"] ?? sectionIds["In progress"], OWNER, { name: "Z" }, database)
    assert.equal(!wrongProject.ok && wrongProject.reason, "not_found", "a section of another project is not found")
    const bad = await reorderSections(projectId, OWNER, [sectionIds["Done"], sectionIds["To do"]], database)
    assert.equal(!bad.ok && bad.reason, "invalid_order")
    const order = [sectionIds["Awaiting client"], sectionIds["To do"], sectionIds["In progress"], sectionIds["Done"]]
    const ok = await reorderSections(projectId, OWNER, order, database)
    assert.ok(ok.ok)
    assert.deepEqual(ok.sections.map((s) => s.id), order)
  })

  it("moving a task into a section sets status; done sets completed_at; leaving done clears it", async () => {
    const id = await newTask("card")
    const toDone = await moveTaskToSection(projectId, sectionIds["Done"], OWNER, { task_id: id, sort_order: null }, database)
    assert.ok(toDone.ok)
    let row = await taskRow(id)
    assert.equal(row.status, "done")
    assert.equal(Number(row.project_id), projectId)
    assert.equal(Number(row.section_id), sectionIds["Done"])
    assert.equal(row.sort_order, 0)
    assert.ok(row.completed_at, "completed_at set by the trigger")
    const back = await moveTaskToSection(projectId, sectionIds["Awaiting client"], OWNER, { task_id: id, sort_order: 5 }, database)
    assert.ok(back.ok)
    row = await taskRow(id)
    assert.equal(row.status, "waiting")
    assert.equal(row.sort_order, 5)
    assert.equal(row.completed_at, null)
    const acts = await client`SELECT action FROM public.codex_activity WHERE entity_type = 'task' AND entity_id = ${id} ORDER BY id`
    assert.deepEqual(acts.map((a) => a.action), ["update", "move_section", "update", "move_section"])
  })

  it("a second task in a section goes last; another project's task is refused; a deleted task is not found", async () => {
    const a = await newTask("a")
    const b = await newTask("b")
    await moveTaskToSection(projectId, sectionIds["To do"], OWNER, { task_id: a, sort_order: null }, database)
    await moveTaskToSection(projectId, sectionIds["To do"], OWNER, { task_id: b, sort_order: null }, database)
    assert.equal((await taskRow(b)).sort_order, 1)
    const privSections = await listSections(privateId, OWNER, database)
    assert.ok(privSections.ok)
    const cross = await moveTaskToSection(privateId, privSections.sections[0].id, OWNER, { task_id: a, sort_order: null }, database)
    assert.equal(!cross.ok && cross.reason, "other_project")
    const wrongSection = await moveTaskToSection(projectId, privSections.sections[0].id, OWNER, { task_id: a, sort_order: null }, database)
    assert.equal(!wrongSection.ok && wrongSection.reason, "not_found")
    await client`UPDATE public.tasks SET deleted_at = now() WHERE id = ${b}`
    const gone = await moveTaskToSection(projectId, sectionIds["Done"], OWNER, { task_id: b, sort_order: null }, database)
    assert.equal(!gone.ok && gone.reason, "task_not_found")
  })

  it("completing moves to the first done section; a task outside the project is not found", async () => {
    const extraDone = await createSection(projectId, OWNER, { name: "Archive", status_category: "done", collapsed_default: true }, database)
    assert.ok(extraDone.ok)
    const id = await newTask("finish me", "in_progress")
    await moveTaskToSection(projectId, sectionIds["In progress"], OWNER, { task_id: id, sort_order: null }, database)
    const done = await completeProjectTask(projectId, id, OWNER, database)
    assert.ok(done.ok)
    assert.equal(done.task.section_id, sectionIds["Done"], "Done (order 3) before Archive (order 4)")
    const row = await taskRow(id)
    assert.equal(row.status, "done")
    assert.ok(row.completed_at)
    const outside = await newTask("loose")
    const r = await completeProjectTask(projectId, outside, OWNER, database)
    assert.equal(!r.ok && r.reason, "task_not_found")
  })

  it("a done help child completed through a section restores its parent (the PATCH path)", async () => {
    const parent = await newTask("parent", "waiting")
    await client`UPDATE public.tasks SET help_prior_status = 'in_progress' WHERE id = ${parent}`
    const [child] = await client`INSERT INTO public.tasks (title, status, parent_task_id, help_requested_by_email) VALUES ('child', 'todo', ${parent}, ${OWNER}) RETURNING id`
    const r = await moveTaskToSection(projectId, sectionIds["Done"], OWNER, { task_id: Number(child.id), sort_order: null }, database)
    assert.ok(r.ok)
    assert.equal((await taskRow(parent)).status, "in_progress")
  })

  it("delete a section only when it has no live tasks; soft-deleted tasks are let go", async () => {
    const holder = await createSection(projectId, OWNER, { name: "Temp", status_category: "todo", collapsed_default: false }, database)
    assert.ok(holder.ok)
    const id = await newTask("in temp")
    await moveTaskToSection(projectId, holder.section.id, OWNER, { task_id: id, sort_order: null }, database)
    const blocked = await deleteSection(projectId, holder.section.id, OWNER, database)
    assert.equal(!blocked.ok && blocked.reason, "section_not_empty")
    await client`UPDATE public.tasks SET deleted_at = now() WHERE id = ${id}`
    const ok = await deleteSection(projectId, holder.section.id, OWNER, database)
    assert.ok(ok.ok)
    assert.equal((await taskRow(id)).section_id, null, "ON DELETE SET NULL on the soft-deleted task")
  })
})

CREATE TABLE IF NOT EXISTS xero_contact_links (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  xero_contact_key text NOT NULL,
  client_id bigint NOT NULL REFERENCES clients(id),
  learned_from text NULL,
  CONSTRAINT uq_xero_contact_links_key UNIQUE (xero_contact_key)
);

CREATE INDEX IF NOT EXISTS idx_xero_contact_links_client
  ON xero_contact_links (client_id);


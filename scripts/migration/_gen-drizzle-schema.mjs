function emitPlanTable(tableName, { stripPublished = false, addFkExtras = [] } = {}) {
  const t = byName[tableName]
  let cols = t.columns
  if (stripPublished) cols = stripPublishedRef(cols)
  let block = `export const ${toCamel(tableName)} = pgTable(\n  "${tableName}",\n  {\n`
  block += cols.join("\n") + "\n  }"
  const extras = [...t.extras, ...addFkExtras]
  if (extras.length) {
    block += `,\n  (table) => [\n${extras.join("\n")}\n  ],\n`
  } else {
    block += `,\n`
  }
  block += `)\n\n`
  return block
}


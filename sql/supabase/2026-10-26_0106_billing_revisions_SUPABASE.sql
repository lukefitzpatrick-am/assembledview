--   The app stays off until BILLING_REVISIONS=on as well.
--
-- Run order
--   1. Run the BEFORE block. Check every expected value.
--   2. Run the DO block. It refuses (nothing done) if the table or the marker
--      already exists, and rolls back if any AFTER check inside fails.
--   3. Run the AFTER block. Check every expected value.
--
-- Measured 2026-10-26 (read-only SELECTs)
--   to_regclass('public.billing_revisions') = NULL
--   latest marker = 0105_client_finance_owners (2026-10-22 18:59 UTC)

-- ===================== BEFORE (read only) =====================
SELECT to_regclass('public.billing_revisions') AS billing_revisions;           -- expect NULL
SELECT count(*) AS marker_rows
  FROM public.migration_markers WHERE key = '0106_billing_revisions';           -- expect 0
SELECT key FROM public.migration_markers ORDER BY applied_at DESC LIMIT 1;     -- expect 0105_client_finance_owners
SELECT to_regclass('public.media_plan_masters') AS masters,
       to_regclass('public.media_plan_versions') AS versions;                   -- expect both non-NULL

-- ===================== CHANGE (one DO block) =====================
DO $$
DECLARE
  n_table   int;
  n_marker  int;
  n_rows    int;
  n_indexes int;
  rls_on    boolean;
BEGIN
  SELECT count(*) INTO n_table FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname = 'billing_revisions' AND c.relkind = 'r';
  SELECT count(*) INTO n_marker FROM public.migration_markers WHERE key = '0106_billing_revisions';
  IF n_table <> 0 OR n_marker <> 0 THEN
    RAISE EXCEPTION 'billing_revisions already exists (table %, marker %). Nothing done.', n_table, n_marker;
  END IF;

  CREATE TABLE public.billing_revisions (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           timestamptz NOT NULL DEFAULT now(),
    master_id            bigint NOT NULL REFERENCES public.media_plan_masters (id) ON DELETE CASCADE,
    mba_number           text NOT NULL,
    base_version_id      bigint NOT NULL REFERENCES public.media_plan_versions (id) ON DELETE CASCADE,
    base_version_number  integer NOT NULL,
    new_version_id       bigint NULL REFERENCES public.media_plan_versions (id) ON DELETE SET NULL,
    new_version_number   integer NULL,
    mode                 text NOT NULL,
    params               jsonb NOT NULL,
    reason               text NOT NULL,
    moved_cents          bigint NOT NULL,
    diff                 jsonb NOT NULL,
    result_hash          text NOT NULL,
    source               text NOT NULL,
    created_by           bigint NOT NULL,
    created_by_name      text NULL,
    restores_revision_id bigint NULL REFERENCES public.billing_revisions (id) ON DELETE SET NULL,
    status               text NOT NULL DEFAULT 'applied',
    CONSTRAINT billing_revisions_mode_check
      CHECK (mode IN ('pull_month', 'bill_remainder', 'bill_amount', 'underspend', 'restore')),
    CONSTRAINT billing_revisions_reason_check CHECK (length(btrim(reason)) > 0),
    CONSTRAINT billing_revisions_source_check CHECK (source IN ('ui', 'ava')),
    CONSTRAINT billing_revisions_status_check CHECK (status IN ('applied', 'restored', 'noted'))
  );

  CREATE INDEX idx_billing_revisions_master_created
    ON public.billing_revisions (master_id, created_at DESC);
  CREATE INDEX idx_billing_revisions_mba
    ON public.billing_revisions (lower(mba_number));
  CREATE UNIQUE INDEX uq_billing_revisions_new_version
    ON public.billing_revisions (new_version_id)
    WHERE new_version_id IS NOT NULL;

  COMMENT ON TABLE public.billing_revisions IS
    'Billing revisions: one row per billing timing change on a published plan (new published version, or a credit note when status = noted).';

  ALTER TABLE public.billing_revisions ENABLE ROW LEVEL SECURITY;

  INSERT INTO public.migration_markers (key, note)
  VALUES ('0106_billing_revisions', 'billing_revisions: audit of billing timing revisions on published plans.');

  -- AFTER checks inside the block. Any failure rolls the whole block back.
  SELECT count(*) INTO n_rows FROM public.billing_revisions;
  IF n_rows <> 0 THEN
    RAISE EXCEPTION 'expected an empty billing_revisions, found % rows', n_rows;
  END IF;
  SELECT count(*) INTO n_indexes FROM pg_indexes
   WHERE schemaname = 'public' AND tablename = 'billing_revisions';
  IF n_indexes <> 4 THEN
    RAISE EXCEPTION 'expected 4 indexes (pkey + 3), found %', n_indexes;
  END IF;
  SELECT relrowsecurity INTO rls_on FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname = 'billing_revisions';
  IF rls_on IS NOT TRUE THEN
    RAISE EXCEPTION 'expected RLS on billing_revisions';
  END IF;
  SELECT count(*) INTO n_marker FROM public.migration_markers WHERE key = '0106_billing_revisions';
  IF n_marker <> 1 THEN
    RAISE EXCEPTION 'expected 1 marker row, found %', n_marker;
  END IF;

  RAISE NOTICE '0106_billing_revisions applied: table empty, 4 indexes, RLS on, marker written.';
END
$$;


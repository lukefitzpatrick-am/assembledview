/**
 * S5b (C-388) against a real Postgres: the alias offer, the one writer
 * (`saveClientAlias`), and both readers of `clients.client_name_aliases`:
 * Fireflies title matching (`loadAttributionContext`) and the relabel Match
 * tab's warehouse join terms (`loadMatchPayload`).
 *
 * Skips unless CLIENT_ALIAS_TEST_DATABASE_URL names a LOCAL database whose
 * name ends in `_alias_test`. It rebuilds that database's public schema.
 */
import assert from "node:assert/strict"
import { after, before, beforeEach, describe, it } from "node:test"

import { drizzle } from "drizzle-orm/postgres-js"
import postgres from "postgres"

import * as schema from "@/db/schema"
import type { Db } from "@/db"
import { classifyTestDatabaseUrl } from "@/lib/testing/testDatabaseGuard"

import { loadAttributionContext } from "../../../fireflies/runSync.js"
import { matchTitleClients } from "../../../fireflies/titleClients.js"
import { loadClientAliasOffer, saveClientAlias } from "../clientAlias.js"
import { loadMatchPayload } from "../match/load.js"

const RAW_URL = process.env.CLIENT_ALIAS_TEST_DATABASE_URL?.trim() ?? ""
const URL_ = (() => {
  if (!RAW_URL || !classifyTestDatabaseUrl(RAW_URL).ok) return null
  try {
    return new URL(RAW_URL).pathname.endsWith("_alias_test") ? RAW_URL : null
  } catch {
    return null
  }
})()
const skip = URL_ ? false : "set CLIENT_ALIAS_TEST_DATABASE_URL to a local database named *_alias_test"

const BASE_SQL = `
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
CREATE TABLE public.clients (id bigint primary key, mp_client_name text, mbaidentifier text,
  client_name_aliases jsonb not null default '[]'::jsonb, m365_is_anchor boolean not null default false);
CREATE TABLE public.media_plan_masters (id bigint generated by default as identity primary key, mba_number text not null,
  client_id bigint, campaign_name text, campaign_end_date date, published_version_id bigint);
CREATE TABLE public.media_plan_versions (id bigint primary key, published_at timestamptz);
CREATE TABLE public.line_items (id bigint generated by default as identity primary key, version_id bigint, line_item_id text,
  channel text, platform text, buy_type text, bursts jsonb);
CREATE TABLE public.client_platform_accounts (client_id bigint, platform text, account_ref text, label text, active boolean);
CREATE TABLE public.client_domains (client_id bigint, email_domain text);
CREATE TABLE public.team_members (email text, name text, email_aliases jsonb, active boolean);
CREATE TABLE public.publisher_domains (publisher_id bigint, email_domain text);
CREATE TABLE public.meeting_title_rules (normalized_title text, target_type text);
INSERT INTO public.clients (id, mp_client_name, mbaidentifier, client_name_aliases) VALUES
  (1, 'Professional Golfers', 'pgaaus', '["PGA"]'), (2, 'Hartmann Wines', 'hartm', '["HART_WINES_2026"]'),
  (3, 'PGA Victoria', 'pgaaus', '[]'), (4, 'Hema Maps', 'hema', '[]'), (5, 'Penfolds', 'penf', '[]'),
  (6, 'Golf Australia', 'golf', '[]');
INSERT INTO public.media_plan_versions VALUES (10, now());
INSERT INTO public.media_plan_masters (mba_number, client_id, campaign_name, published_version_id) VALUES
  ('PGAAUS015', 1, 'Tour', 10), ('hartm001', 2, 'Vintage', null), ('noclient001', null, 'x', null),
  ('pgaaus016', 1, 'Tour 2', null);
`

const preview = (mbaNumber: string | null) => ({ channel: "Social - Meta", platformEntityId: "120200001", mbaNumber })
/** The entity's campaign name; the delivery check (REGEXP_REPLACE) answers `deliveryLines`, or throws when given an Error. */
const warehouse =
  (campaign: string | null, deliveryLines: string[] | Error = []) =>
  async (sqlText: string): Promise<Record<string, unknown>[]> => {
    if (sqlText.includes("REGEXP_REPLACE")) {
      if (deliveryLines instanceof Error) throw deliveryLines
      return deliveryLines.map((RID) => ({ RID }))
    }
    return campaign == null ? [] : [{ CAMPAIGN_NAME: campaign }]
  }

describe("client name aliases on Postgres (S5b)", { skip }, () => {
  let client: ReturnType<typeof postgres>
  let db: Db
  const aliases = async (id: number) =>
    ((await client`SELECT client_name_aliases AS a FROM public.clients WHERE id = ${id}`)[0]!.a as string[])

  before(async () => {
    client = postgres(URL_!, { max: 1, onnotice: () => {} })
    db = drizzle(client, { schema }) as unknown as Db
  })
  beforeEach(async () => {
    await client.unsafe(BASE_SQL)
  })
  after(async () => {
    await client?.unsafe("DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public;")
    await client?.end()
  })

  it("offers the warehouse campaign name for the target plan's client (MBA in any case)", async () => {
    const offer = await loadClientAliasOffer(preview("pgaaus015"), warehouse("PGA_AU_Tour_2026"), db)
    assert.deepEqual(offer, { campaignName: "PGA_AU_Tour_2026", clientId: 1, clientName: "Professional Golfers", refusal: null })
  })

  it("refuses a generic name, another client's alias, a plan with no client and a blank campaign", async () => {
    assert.match((await loadClientAliasOffer(preview("pgaaus015"), warehouse("Prospecting"), db)).refusal ?? "", /no digit or separator/)
    assert.match(
      (await loadClientAliasOffer(preview("pgaaus015"), warehouse("hart-wines 2026"), db)).refusal ?? "",
      /another client's name or alias/,
    )
    assert.match((await loadClientAliasOffer(preview("noclient001"), warehouse("PGA_AU_2026"), db)).refusal ?? "", /no client/)
    assert.match((await loadClientAliasOffer(preview(null), warehouse("PGA_AU_2026"), db)).refusal ?? "", /no client/)
    assert.match((await loadClientAliasOffer(preview("pgaaus015"), warehouse(null), db)).refusal ?? "", /no campaign name/)
  })

  it("refuses the reviewer's names: other clients' phrases, or delivery on another client's plan", async () => {
    for (const name of ["Hema-Maps", "Penfolds-2026", "Golf-Australia", "Hartmann_2026"]) {
      assert.match((await loadClientAliasOffer(preview("pgaaus015"), warehouse(name), db)).refusal ?? "", /another client's name or alias/, name)
    }
    // A client in the same MBA identifier group shares Fireflies phrases, so its words are not "another client's".
    assert.equal((await loadClientAliasOffer(preview("pgaaus015"), warehouse("PGA-Victoria-2026"), db)).refusal, null)
    for (const name of ["Always-On", "FY26_Brand", "Brand-Awareness"]) {
      const offer = await loadClientAliasOffer(preview("pgaaus015"), warehouse(name, ["hartm001sm1", "pgaaus015sm1"]), db)
      assert.equal(offer.refusal, `"${name}" has delivery on hartm001, another client's plan, in the last 30 days.`, name)
    }
    // Delivery only on this client's own plans is fine.
    assert.equal((await loadClientAliasOffer(preview("pgaaus015"), warehouse("Always-On", ["pgaaus016sm2", ""]), db)).refusal, null)
  })

  it("refuses delivery on a plan with no client: that is not this client's plan either", async () => {
    const offer = await loadClientAliasOffer(preview("pgaaus015"), warehouse("Brand-Q3-2026", ["noclient001sm1"]), db)
    assert.equal(offer.refusal, '"Brand-Q3-2026" has delivery on noclient001, another client\'s plan, in the last 30 days.')
  })

  it("fails closed when the delivery check passes its deadline", async () => {
    const hang = async (sqlText: string): Promise<Record<string, unknown>[]> =>
      sqlText.includes("REGEXP_REPLACE") ? new Promise(() => {}) : [{ CAMPAIGN_NAME: "Always-On" }]
    await assert.rejects(loadClientAliasOffer(preview("pgaaus015"), hang, db, 50), /passed 50 ms/)
  })

  it("fails closed: a warehouse read that fails throws, so the handlers refuse", async () => {
    await assert.rejects(loadClientAliasOffer(preview("pgaaus015"), warehouse("Always-On", new Error("snowflake down")), db), /snowflake down/)
  })

  it("saves once; never a second time, and never for another client", async () => {
    assert.equal(await saveClientAlias(1, " PGA_AU_Tour_2026 ", db), true)
    assert.deepEqual(await aliases(1), ["PGA", "PGA_AU_Tour_2026"])
    assert.equal(await saveClientAlias(1, "pga_au_tour_2026", db), false)
    assert.equal(await saveClientAlias(2, "PGA_AU_TOUR_2026", db), false)
    assert.equal(await saveClientAlias(2, "pga au tour 2026", db), false)
    assert.deepEqual(await aliases(1), ["PGA", "PGA_AU_Tour_2026"])
    assert.deepEqual(await aliases(2), ["HART_WINES_2026"])
  })

  it("two clients saving the same name at once: exactly one wins", async () => {
    const pool = postgres(URL_!, { max: 2, onnotice: () => {} })
    const db2 = drizzle(pool, { schema }) as unknown as Db
    try {
      const results = await Promise.all([saveClientAlias(1, "SHARED_2026", db2), saveClientAlias(2, "SHARED_2026", db2)])
      assert.deepEqual(results.filter(Boolean).length, 1)
    } finally {
      await pool.end()
    }
  })

  it("Fireflies and the Match tab both see a saved alias", async () => {
    await saveClientAlias(1, "PGA_AU_Tour_2026", db)

    const ctx = await loadAttributionContext(db)
    const hits = matchTitleClients("Weekly PGA_AU_Tour_2026 status", ctx.titleClients)
    assert.deepEqual(hits.map((h) => h.clientId), [1])
    // A stored name alias from before S5b reaches Fireflies too.
    await client`UPDATE public.clients SET client_name_aliases = '["Go Golfer"]' WHERE id = 2`
    const ctx2 = await loadAttributionContext(db)
    assert.deepEqual(matchTitleClients("Go Golfer catch up", ctx2.titleClients).map((h) => h.clientId), [2])

    const binds: unknown[][] = []
    await loadMatchPayload(1, {
      fresh: true,
      db,
      query: async (_sql: string, b: unknown[] = []) => {
        binds.push(b)
        return []
      },
    })
    assert.ok(binds[0]!.includes("pga_au_tour_2026"), JSON.stringify(binds[0]))
  })
})

function renderTable(t, { needEnums }) {
  const exportName = toCamel(t.name)
  let block = `export const ${exportName} = pgTable(\n  "${t.name}",\n  {\n`
  block += t.columns.join("\n") + "\n"
  block += `  }`
  if (t.extras.length) {
    block += `,\n  (table) => [\n${t.extras.join("\n")}\n  ],\n`
  } else {
    block += `,\n`
  }
  block += `)\n\n`
  return block
}


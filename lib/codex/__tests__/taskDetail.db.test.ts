/**
 * Codex task detail store (B40) against a real Postgres with migration 0118
 * applied: subtasks never act as help children, then (later patches) the
 * detail read, subtasks, dates, assigned by, milestones and custom fields.
 *
 * Skips unless CODEX_PROJECTS_TEST_DATABASE_URL names a LOCAL database whose
 * name ends in `_codex_test`. It works in a sibling database
 * `<name>_detail_codex_test` (created if missing) so it can run beside the
 * other projects suites, and drops and rebuilds that database's public
 * schema. It never reads .env.local and never reaches production.
 */
import assert from "node:assert/strict"
import fs from "node:fs"
import path from "node:path"
import { after, before, describe, it } from "node:test"

import postgres from "postgres"
import { drizzle } from "drizzle-orm/postgres-js"

import * as schema from "@/db/schema"
import type { Db } from "@/db"
import { classifyTestDatabaseUrl } from "../../testing/testDatabaseGuard"
import { getTask, softDeleteTask, updateTask } from "../repo.js"
import { createProject, resetProjectsMarkerCacheForTests } from "../projectsRepo.js"

const RAW_URL = process.env.CODEX_PROJECTS_TEST_DATABASE_URL?.trim() ?? ""

function detailUrl(url: string): string | null {
  if (!url || !classifyTestDatabaseUrl(url).ok) return null
  try {
    const u = new URL(url)
    const name = u.pathname.replace(/^\//, "")
    if (!name.endsWith("_codex_test")) return null
    u.pathname = `/${name.replace(/_codex_test$/, "_detail_codex_test")}`
    return u.toString()
  } catch {
    return null
  }
}

const DETAIL_URL = detailUrl(RAW_URL)
const skip = DETAIL_URL ? false : "set CODEX_PROJECTS_TEST_DATABASE_URL to a local database named *_codex_test"


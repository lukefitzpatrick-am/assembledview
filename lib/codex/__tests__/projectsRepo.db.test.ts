    const back = await moveTaskToSection(projectId, sectionIds["Awaiting client"], OWNER, { task_id: id, sort_order: 5 }, database)
    assert.ok(back.ok)
    row = await taskRow(id)
    assert.equal(row.status, "waiting")
    assert.equal(row.sort_order, 5)
    assert.equal(row.completed_at, null)
    const acts = await client`SELECT action FROM public.codex_activity WHERE entity_type = 'task' AND entity_id = ${id} ORDER BY id`

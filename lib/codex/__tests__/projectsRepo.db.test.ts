/**
 * Codex projects store (S1, B38) against a real Postgres with migration 0118
 * applied. Skips unless CODEX_PROJECTS_TEST_DATABASE_URL names a LOCAL
 * database whose name ends in `_codex_test` (the test drops and rebuilds its
 * public schema). It never reads .env.local and never reaches production.
 *
 *   createdb -h 127.0.0.1 -p 5432 av_codex_test
 *   CODEX_PROJECTS_TEST_DATABASE_URL=postgres://postgres@127.0.0.1:5432/av_codex_test npm run test:codex-projects
 *
 * Builds a minimal replica of tasks (live columns and checks as of 13 Nov
 * 2026), then runs db/migrations/0118_codex_s1_projects.sql itself, so the
 * migration, the sync trigger and the raw SQL in projectsRepo.ts are all
 * exercised.
 */

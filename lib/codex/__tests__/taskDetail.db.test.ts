      const parent = await newTask("Parent", { status: "in_progress" })
      const sub = await newTask("Sub", { parent, type: "subtask" })
      await updateTask(sub, { status: "done" }, OWNER, database)
      assert.equal((await taskRow(parent)).status, "in_progress")
      await client`UPDATE public.tasks SET status = 'todo' WHERE id = ${parent}`

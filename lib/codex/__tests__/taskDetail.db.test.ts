const OWNER = "owner@assembledmedia.com.au"
const MIA = "mia@assembledmedia.com.au"

describe("codex task detail store on Postgres (0118 applied)", { skip }, () => {
  let client: ReturnType<typeof postgres>
  let database: Db
  let projectId = 0
  const sec: Record<string, number> = {}

  async function taskRow(id: number) {
    const [row] = await client`SELECT id, title, status, task_type, project_id::int AS project_id, section_id::int AS section_id,
      sort_order, parent_task_id::int AS parent_task_id, assignee_email, assigned_by_email, start_on::text AS start_on,
      due_on::text AS due_on, due_date, custom_values, help_prior_status, deleted_at FROM public.tasks WHERE id = ${id}`
    return row
  }
  async function newTask(title: string, extra: { status?: string; parent?: number; type?: string; project?: number } = {}): Promise<number> {
    const [row] = await client`INSERT INTO public.tasks (title, status, parent_task_id, task_type, project_id)
      VALUES (${title}, ${extra.status ?? "todo"}, ${extra.parent ?? null}, ${extra.type ?? "task"}, ${extra.project ?? null}) RETURNING id`
    return Number(row.id)
  }

  before(async () => {
    const admin = postgres(RAW_URL, { max: 1, onnotice: () => {} })
    const name = new URL(DETAIL_URL!).pathname.slice(1)
    try {
      await admin.unsafe(`CREATE DATABASE "${name}"`)
    } catch (err) {
      if ((err as { code?: string }).code !== "42P04") throw err
    } finally {
      await admin.end({ timeout: 5 })
    }
    client = postgres(DETAIL_URL!, { max: 2, onnotice: () => {} })
    await client.unsafe(BASE_SQL)
    await client.unsafe(fs.readFileSync(path.join(process.cwd(), "db/migrations/0118_codex_s1_projects.sql"), "utf8"))
    resetProjectsMarkerCacheForTests()
    database = drizzle(client, { schema }) as unknown as Db
    const r = await createProject(
      OWNER,
      {
        name: "Digital desk", kind: "ops", client_id: 42, mba_number: "dd001", owner_email: null, is_private: false,
        start_on: null, due_on: null, members: [],
        sections: [
          { name: "Inbound", status_category: "todo" },
          { name: "This week", status_category: "in_progress" },
          { name: "Done", status_category: "done" },
        ],
      },
      database
    )
    assert.ok(r.ok)
    projectId = r.project.id
    for (const s of r.sections) sec[s.name] = s.id
  })

  after(async () => {
    resetProjectsMarkerCacheForTests()
    await client?.end({ timeout: 5 })
  })

  describe("subtasks are never help children (B40-02)", () => {
    it("completing or reopening the last subtask leaves the parent's status alone", async () => {
      const parent = await newTask("Parent", { status: "in_progress" })
      const sub = await newTask("Sub", { parent, type: "subtask" })
      await updateTask(sub, { status: "done" }, OWNER, database)
      assert.equal((await taskRow(parent)).status, "in_progress")
      await client`UPDATE public.tasks SET status = 'todo' WHERE id = ${parent}`
      await updateTask(sub, { status: "todo" }, OWNER, database)
      assert.equal((await taskRow(parent)).status, "todo", "reopening a subtask does not put the parent in waiting")
    })

    it("a help child still restores its parent; an open subtask beside it does not hold the parent in waiting", async () => {
      const parent = await newTask("Asked", { status: "waiting" })
      await client`UPDATE public.tasks SET help_prior_status = 'in_progress' WHERE id = ${parent}`
      const help = await newTask("Help: Asked", { parent })
      await newTask("Open subtask", { parent, type: "subtask" })
      await updateTask(help, { status: "done" }, OWNER, database)
      assert.equal((await taskRow(parent)).status, "in_progress")
    })

    it("deleting an open subtask never completes a waiting parent", async () => {
      const parent = await newTask("Waiting parent", { status: "waiting" })
      await client`UPDATE public.tasks SET help_prior_status = 'todo' WHERE id = ${parent}`
      const help = await newTask("Help", { parent })
      const sub = await newTask("Sub", { parent, type: "subtask" })
      assert.equal(await softDeleteTask(sub, OWNER, database), true)
      assert.equal((await taskRow(parent)).status, "waiting")
      const alone = await newTask("Waiting, subtask only", { status: "waiting" })
      await client`UPDATE public.tasks SET help_prior_status = 'todo' WHERE id = ${alone}`
      const onlySub = await newTask("Only sub", { parent: alone, type: "subtask" })
      assert.equal(await softDeleteTask(onlySub, OWNER, database), true)
      assert.equal((await taskRow(alone)).status, "waiting", "a subtask's delete never restores the parent")
      assert.equal(await softDeleteTask(help, OWNER, database), true)
      assert.equal((await taskRow(parent)).status, "todo", "the help child's delete still restores")
    })

    it("the detail lists help children as Waiting on, never subtasks; a subtask shows no help parent snapshot", async () => {
      const parent = await newTask("Has both")
      const help = await newTask("Help: Has both", { parent })
      const sub = await newTask("Sub of both", { parent, type: "subtask" })
      const detail = await getTask(parent, database)
      assert.deepEqual(detail?.children?.map((c) => c.id), [help])
      const subDetail = await getTask(sub, database)
      assert.equal(subDetail?.parent ?? null, null)
      const helpDetail = await getTask(help, database)
      assert.equal(helpDetail?.parent?.id, parent)
    })
  })

  it("project fixture exists", () => {
    assert.ok(projectId > 0 && sec["Done"] > 0)
  })
})

-- ===================== CHANGE (one DO block) =====================
DO $$
DECLARE
  n_table   int;
  n_marker  int;
  n_rows    int;
  n_indexes int;
  rls_on    boolean;
BEGIN
  SELECT count(*) INTO n_table FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname = 'ap_bill_line_matches' AND c.relkind = 'r';
  SELECT count(*) INTO n_marker FROM public.migration_markers WHERE key = '0107_ap_bill_line_matches';
  IF n_table <> 0 OR n_marker <> 0 THEN
    RAISE EXCEPTION 'ap_bill_line_matches already exists (table %, marker %). Nothing done.', n_table, n_marker;
  END IF;

  CREATE TABLE public.ap_bill_line_matches (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         timestamptz NOT NULL DEFAULT now(),
    xero_invoice_id    text NOT NULL,
    xero_line_item_id  text NOT NULL,
    line_index         integer NOT NULL,
    mba_number         text NOT NULL,
    line_item_id       text NOT NULL,
    month              date NOT NULL,
    amount_cents       bigint NOT NULL,
    matched_by         text NOT NULL,
    matched_by_name    text NULL,
    matched_at         timestamptz NOT NULL DEFAULT now(),
    note               text NULL,
    CONSTRAINT ap_bill_line_matches_line_index_check CHECK (line_index >= 0),
    CONSTRAINT ap_bill_line_matches_month_check CHECK (EXTRACT(DAY FROM month) = 1),
    CONSTRAINT ap_bill_line_matches_ids_check
      CHECK (length(btrim(xero_invoice_id)) > 0 AND length(btrim(xero_line_item_id)) > 0
        AND length(btrim(mba_number)) > 0 AND length(btrim(line_item_id)) > 0
        AND length(btrim(matched_by)) > 0)
  );

  CREATE UNIQUE INDEX uq_ap_bill_line_matches_bill_line
    ON public.ap_bill_line_matches (xero_invoice_id, xero_line_item_id);
  CREATE INDEX idx_ap_bill_line_matches_line
    ON public.ap_bill_line_matches (lower(line_item_id));

  COMMENT ON TABLE public.ap_bill_line_matches IS
    'Saved manual matches of supplier (Xero AP) bill lines to plan lines and months, for the fixed cost margin report. One row per bill line.';

  ALTER TABLE public.ap_bill_line_matches ENABLE ROW LEVEL SECURITY;

  INSERT INTO public.migration_markers (key, note)
  VALUES ('0107_ap_bill_line_matches', 'ap_bill_line_matches: saved manual matches of AP bill lines to plan lines (MAR-4).');

  -- AFTER checks inside the block. Any failure rolls the whole block back.
  SELECT count(*) INTO n_rows FROM public.ap_bill_line_matches;
  IF n_rows <> 0 THEN
    RAISE EXCEPTION 'expected an empty ap_bill_line_matches, found % rows', n_rows;
  END IF;
  SELECT count(*) INTO n_indexes FROM pg_indexes
   WHERE schemaname = 'public' AND tablename = 'ap_bill_line_matches';
  IF n_indexes <> 3 THEN
    RAISE EXCEPTION 'expected 3 indexes (pkey + 2), found %', n_indexes;
  END IF;
  SELECT relrowsecurity INTO rls_on FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname = 'ap_bill_line_matches';
  IF rls_on IS NOT TRUE THEN
    RAISE EXCEPTION 'expected RLS on ap_bill_line_matches';
  END IF;
  SELECT count(*) INTO n_marker FROM public.migration_markers WHERE key = '0107_ap_bill_line_matches';
  IF n_marker <> 1 THEN
    RAISE EXCEPTION 'expected 1 marker row, found %', n_marker;
  END IF;

  RAISE NOTICE '0107_ap_bill_line_matches applied: table empty, 3 indexes, RLS on, marker written.';
END
$$;


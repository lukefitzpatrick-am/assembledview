-- ---------------------------------------------------------------------------
-- 3. xero_invoice_matches
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS xero_invoice_matches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  xero_invoice_id text NOT NULL,
  run_item_id bigint NULL REFERENCES finance_run_items(id) ON DELETE SET NULL,
  method xero_match_method NOT NULL,
  confidence numeric(5,4) NOT NULL DEFAULT 0,
  delta_cents bigint NOT NULL DEFAULT 0,
  status xero_match_status NOT NULL DEFAULT 'matched',
  decided_by text NULL,
  decided_at timestamptz NULL,
  card_kind text NULL,
  detail text NULL,
  period_month date NULL,
  CONSTRAINT uq_xero_invoice_matches_invoice UNIQUE (xero_invoice_id)
);

CREATE INDEX IF NOT EXISTS idx_xero_invoice_matches_run_item
  ON xero_invoice_matches (run_item_id);
CREATE INDEX IF NOT EXISTS idx_xero_invoice_matches_status
  ON xero_invoice_matches (status);
CREATE INDEX IF NOT EXISTS idx_xero_invoice_matches_period
  ON xero_invoice_matches (period_month);

ALTER TABLE xero_invoice_matches ENABLE ROW LEVEL SECURITY;


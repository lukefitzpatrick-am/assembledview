export const RAW_URL = process.env.CODEX_PROJECTS_TEST_DATABASE_URL?.trim() ?? ""

export function siblingUrl(url: string, suffix: string): string | null {
  if (!url || !classifyTestDatabaseUrl(url).ok) return null
  try {
    const u = new URL(url)
    const name = u.pathname.replace(/^\//, "")
    if (!name.endsWith("_codex_test")) return null
    u.pathname = `/${name.replace(/_codex_test$/, `_${suffix}_codex_test`)}`
    return u.toString()
  } catch {
    return null
  }
}


export async function createDatabase(url: string): Promise<ReturnType<typeof postgres>> {
  const admin = postgres(RAW_URL, { max: 1, onnotice: () => {} })
  const name = new URL(url).pathname.slice(1)
  try {
    await admin.unsafe(`CREATE DATABASE "${name}"`)
  } catch (err) {
    if ((err as { code?: string }).code !== "42P04") throw err
  } finally {
    await admin.end({ timeout: 5 })
  }
  const client = postgres(url, { max: 4, onnotice: () => {} })
  await client.unsafe(BASE_SQL)
  return client
}


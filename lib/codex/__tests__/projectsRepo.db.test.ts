const RAW_URL = process.env.CODEX_PROJECTS_TEST_DATABASE_URL?.trim() ?? ""

function usableUrl(url: string): boolean {
  if (!url) return false
  if (!classifyTestDatabaseUrl(url).ok) return false
  try {
    return new URL(url).pathname.replace(/^\//, "").endsWith("_codex_test")
  } catch {
    return false
  }
}

const skip = usableUrl(RAW_URL)
  ? false
  : "set CODEX_PROJECTS_TEST_DATABASE_URL to a local database named *_codex_test"

const BASE_SQL = `
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
SET TimeZone = 'UTC';
CREATE TABLE public.migration_markers (key text primary key, applied_at timestamptz not null default now(), note text);
CREATE TABLE public.clients (id bigint primary key);
CREATE TABLE public.client_notes (id bigint generated by default as identity primary key);
CREATE TABLE public.task_templates (id bigint generated by default as identity primary key, name text, description text, created_at timestamptz not null default now());
CREATE TABLE public.tasks (
  id bigint generated by default as identity primary key, client_id bigint, mba_number text, title text not null, description text,
  status text not null default 'todo' CONSTRAINT tasks_status_check CHECK (status in ('backlog','todo','in_progress','waiting','done')),
  priority text default 'normal', due_date timestamptz, recurring_rule text, template_id bigint references public.task_templates(id) on delete set null,
  client_visible boolean, created_at timestamptz not null default now(), updated_at timestamptz, assignee_email text, assignee_name text,
  created_by_email text, source text not null default 'manual', source_note_id bigint references public.client_notes(id) on delete set null,
  category text, deleted_at timestamptz, auto_created boolean not null default false, ava_auto_key text, estimated_minutes integer,
  parent_task_id bigint references public.tasks(id) on delete set null, help_requested_by_email text, help_prior_status text,
  CONSTRAINT tasks_priority_check CHECK (priority IS NULL OR priority IN ('low','normal','high')),
  CONSTRAINT tasks_source_check CHECK (source IN ('manual','ava','template','recurring') OR source LIKE 'profile:%'));
CREATE TABLE public.task_comments (id bigint generated by default as identity primary key, task_id bigint references public.tasks(id) on delete cascade,
  body text, created_at timestamptz not null default now(), author_email text, author_name text, author_kind text not null default 'user');
CREATE TABLE public.codex_activity (id bigint generated always as identity primary key, entity_type text not null, entity_id bigint not null,
  actor_email text, actor_kind text not null default 'user', action text not null, before jsonb, after jsonb, created_at timestamptz not null default now());
INSERT INTO public.clients (id) VALUES (42);
INSERT INTO public.tasks (title, due_date, status) VALUES ('old due', '2026-08-14', 'todo');
`


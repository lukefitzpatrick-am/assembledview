      assert.equal(await softDeleteTask(sub, OWNER, database), true)
      assert.equal((await taskRow(parent)).status, "waiting")
      const alone = await newTask("Waiting, subtask only", { status: "waiting" })
      await client`UPDATE public.tasks SET help_prior_status = 'todo' WHERE id = ${alone}`
      const onlySub = await newTask("Only sub", { parent: alone, type: "subtask" })
      assert.equal(await softDeleteTask(onlySub, OWNER, database), true)
      assert.equal((await taskRow(alone)).status, "waiting", "a subtask's delete never restores the parent")
      assert.equal(await softDeleteTask(help, OWNER, database), true)
      assert.equal((await taskRow(parent)).status, "todo", "the help child's delete still restores")

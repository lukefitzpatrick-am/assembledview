-- 0111_feature_switches: guarded run file for Luke.
-- Supabase project slpdibnxtpdlttbbczvg. Luke runs this by hand in the SQL Editor.
-- Same DDL as db/migrations/0111_feature_switches.sql (the repo copy, AUTHOR ONLY).
--
-- What it does
--   Creates public.feature_switches and public.feature_switch_events (both
--   empty, RLS on) and writes the marker 0111_feature_switches. Touches no
--   existing rows. No switch rows are seeded: until someone toggles a switch
--   on /admin/features, every feature keeps reading its old env var.
--
-- Run order
--   1. Run the BEFORE block. Check every expected value.
--   2. Run the DO block. It refuses (nothing done) if the marker or a table
--      already exists, and rolls back if any AFTER check inside fails.
--   3. Run the AFTER block. Check every expected value.

-- ===================== BEFORE (read only) =====================
SELECT to_regclass('public.feature_switches') AS feature_switches,             -- expect NULL
       to_regclass('public.feature_switch_events') AS feature_switch_events;   -- expect NULL
SELECT count(*) AS marker_rows FROM public.migration_markers
 WHERE key = '0111_feature_switches';                                          -- expect 0

-- ===================== CHANGE (one DO block) =====================
DO $$
DECLARE
  n_tables  integer;
  n_rls     integer;
  n_rows    bigint;
  n_marker  integer;
BEGIN
  IF EXISTS (SELECT 1 FROM public.migration_markers WHERE key = '0111_feature_switches') THEN
    RAISE EXCEPTION 'marker 0111_feature_switches already exists - nothing done';
  END IF;
  IF to_regclass('public.feature_switches') IS NOT NULL
     OR to_regclass('public.feature_switch_events') IS NOT NULL THEN
    RAISE EXCEPTION 'a feature switch table already exists - nothing done';
  END IF;

  CREATE TABLE IF NOT EXISTS public.feature_switches (
    key              text PRIMARY KEY,
    enabled          boolean NOT NULL,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    updated_by       bigint NULL,
    updated_by_name  text NULL,
    note             text NULL,
    CONSTRAINT feature_switches_key_check CHECK (key ~ '^[a-z0-9_]{1,64}$'),
    CONSTRAINT feature_switches_note_check CHECK (note IS NULL OR length(note) <= 500)
  );

  CREATE TABLE IF NOT EXISTS public.feature_switch_events (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamptz NOT NULL DEFAULT now(),
    key              text NOT NULL,
    from_enabled     boolean NULL,
    to_enabled       boolean NOT NULL,
    changed_by       bigint NULL,
    changed_by_name  text NULL,
    note             text NULL,
    CONSTRAINT feature_switch_events_key_check CHECK (key ~ '^[a-z0-9_]{1,64}$'),
    CONSTRAINT feature_switch_events_note_check CHECK (note IS NULL OR length(note) <= 500)
  );
  CREATE INDEX IF NOT EXISTS idx_feature_switch_events_key_created
    ON public.feature_switch_events (key, created_at DESC NULLS LAST);

  COMMENT ON TABLE public.feature_switches IS
    'On/off feature switches set on /admin/features. No row = the old env var, else off.';
  COMMENT ON TABLE public.feature_switch_events IS
    'Audit of every feature switch change: from, to, who, when, note.';

  ALTER TABLE public.feature_switches ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.feature_switch_events ENABLE ROW LEVEL SECURITY;

  INSERT INTO public.migration_markers (key, note)
  VALUES ('0111_feature_switches', 'feature_switches and feature_switch_events (admin feature switches page). No rows seeded.');

  -- AFTER checks inside the block. Any failure rolls the whole block back.
  SELECT count(*) INTO n_tables FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname IN ('feature_switches', 'feature_switch_events');
  IF n_tables <> 2 THEN
    RAISE EXCEPTION 'expected 2 feature switch tables, found %', n_tables;
  END IF;
  SELECT count(*) INTO n_rls FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname IN ('feature_switches', 'feature_switch_events')
     AND c.relrowsecurity;
  IF n_rls <> 2 THEN
    RAISE EXCEPTION 'expected RLS on both feature switch tables, found %', n_rls;
  END IF;
  SELECT (SELECT count(*) FROM public.feature_switches) + (SELECT count(*) FROM public.feature_switch_events) INTO n_rows;
  IF n_rows <> 0 THEN
    RAISE EXCEPTION 'expected empty feature switch tables, found % rows', n_rows;
  END IF;
  SELECT count(*) INTO n_marker FROM public.migration_markers WHERE key = '0111_feature_switches';
  IF n_marker <> 1 THEN
    RAISE EXCEPTION 'expected 1 marker row, found %', n_marker;
  END IF;

  RAISE NOTICE '0111_feature_switches applied: 2 tables (empty, RLS on), marker written. No switch rows: every feature still reads its env var.';
END
$$;

-- ===================== AFTER (read only) =====================
SELECT to_regclass('public.feature_switches') AS feature_switches,             -- expect feature_switches
       to_regclass('public.feature_switch_events') AS feature_switch_events;   -- expect feature_switch_events
SELECT relname, relrowsecurity FROM pg_class
 WHERE relname IN ('feature_switches', 'feature_switch_events') ORDER BY relname;  -- expect 2 rows, both true
SELECT count(*) AS switch_rows FROM public.feature_switches;                   -- expect 0
SELECT key FROM public.migration_markers WHERE key = '0111_feature_switches';   -- expect 1 row


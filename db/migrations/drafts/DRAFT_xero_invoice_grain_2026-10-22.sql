BEGIN;

-- 1. Grain per client -----------------------------------------------------
-- G1 one invoice per client, MBA, month (default; no row = G1)
-- G2 one invoice per client, MBA, month, supplier
-- G3 one invoice per client, MBA, month, PO (lines placed by the PO register)
-- G4 one invoice per client, month, across MBAs (consolidated)
CREATE TABLE IF NOT EXISTS client_invoice_grain (
  client_id bigint PRIMARY KEY REFERENCES clients(id) ON DELETE CASCADE,
  grain text NOT NULL DEFAULT 'G1'
    CHECK (grain IN ('G1', 'G2', 'G3', 'G4')),
  -- First billing month the grain applies to. Earlier months keep G1.
  effective_from_month text NOT NULL
    CHECK (effective_from_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  -- G3 only: what happens to a line no PO covers. 'block' stops the batch.
  unassigned_line_rule text NOT NULL DEFAULT 'block'
    CHECK (unassigned_line_rule IN ('block', 'own_invoice')),
  notes text NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by bigint NULL REFERENCES team_members(id) ON DELETE SET NULL
);

-- 2. PO register ----------------------------------------------------------
-- One row per client purchase order, on the client's terms. A PO covers
-- lines by scope: the whole MBA, one supplier inside an MBA, or an explicit
-- line list (client_purchase_order_lines). Most specific wins:
--   line list > (MBA, supplier) > MBA > client-wide.
CREATE TABLE IF NOT EXISTS client_purchase_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  client_id bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  po_number text NOT NULL CHECK (btrim(po_number) <> ''),
  mba_number text NULL,
  -- Normalised supplier key (lower, trimmed publisher/network/platform).
  supplier_key text NULL,
  supplier_label text NULL,
  -- Months the PO may bill. Null = open.
  month_from text NULL CHECK (month_from IS NULL OR month_from ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  month_to text NULL CHECK (month_to IS NULL OR month_to ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  -- Drawdown cap ex-GST. Null = no cap. Remaining = cap minus planned invoices on it.
  amount_cap_cents bigint NULL CHECK (amount_cap_cents IS NULL OR amount_cap_cents >= 0),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed', 'cancelled')),
  source text NOT NULL DEFAULT 'client' CHECK (source IN ('client', 'import', 'manual')),
  notes text NULL,
  created_by bigint NULL REFERENCES team_members(id) ON DELETE SET NULL,
  CONSTRAINT ck_client_po_supplier_needs_mba CHECK (supplier_key IS NULL OR mba_number IS NOT NULL)
);

-- The same PO number can recur across clients; within a client it is unique per scope.
CREATE UNIQUE INDEX IF NOT EXISTS uq_client_po_scope
  ON client_purchase_orders (client_id, po_number, coalesce(lower(mba_number), ''), coalesce(supplier_key, ''));
CREATE INDEX IF NOT EXISTS idx_client_po_mba
  ON client_purchase_orders (lower(mba_number));

-- Explicit line assignment for client-defined splits that are not by supplier
-- (e.g. PENFOLD015 'Bin 707 amplification' on its own PO).
CREATE TABLE IF NOT EXISTS client_purchase_order_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id bigint NOT NULL REFERENCES client_purchase_orders(id) ON DELETE CASCADE,
  mba_number text NOT NULL,
  line_item_id text NOT NULL,
  -- Null = every billing month the PO covers.
  billing_month text NULL CHECK (billing_month IS NULL OR billing_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  -- Null = the whole line amount for the month. Set = a fixed part of it (split line, Q9).
  amount_cents bigint NULL CHECK (amount_cents IS NULL OR amount_cents >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_client_po_lines
  ON client_purchase_order_lines (purchase_order_id, lower(mba_number), line_item_id, coalesce(billing_month, '*'));

CREATE INDEX IF NOT EXISTS idx_client_po_lines_line
  ON client_purchase_order_lines (lower(mba_number), line_item_id);

-- 3. Planned invoices -----------------------------------------------------
-- One row per invoice AV expects in Xero. Built at approve from the record,
-- the client grain and the PO register. G1: one planned invoice per record.
-- G2/G3: several per record. G4: one planned invoice over several records.
CREATE TABLE IF NOT EXISTS finance_planned_invoices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- 'media:{mba}:{YYYY-MM}#all'           G1
  -- 'media:{mba}:{YYYY-MM}#s:{supplier}'   G2
  -- 'media:{mba}:{YYYY-MM}#po:{po}'        G3
  -- 'client:{client_id}:{YYYY-MM}#all'     G4
  planned_invoice_key text NOT NULL,
  client_id bigint NOT NULL,
  billing_month text NOT NULL CHECK (billing_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  grain text NOT NULL CHECK (grain IN ('G1', 'G2', 'G3', 'G4')),
  purchase_order_id bigint NULL REFERENCES client_purchase_orders(id) ON DELETE SET NULL,
  po_number text NULL,
  supplier_label text NULL,
  -- D7: 'PO {po} ({MBA})' or '({MBA})'. MBA last, in brackets.
  reference text NOT NULL,
  expected_cents bigint NOT NULL,
  lines_hash text NULL,
  status text NOT NULL DEFAULT 'planned'
    CHECK (status IN ('planned', 'exported', 'pushed', 'matched', 'stale', 'superseded')),
  -- Set by the matcher (or by construction at push, FP-4).
  matched_xero_invoice_id text NULL,
  matched_at timestamptz NULL,
  matched_by text NULL,
  xero_match_resolution text NULL,
  pushed_xero_invoice_id text NULL,
  pushed_at timestamptz NULL,
  pushed_by bigint NULL REFERENCES team_members(id) ON DELETE SET NULL,
  superseded_by bigint NULL REFERENCES finance_planned_invoices(id) ON DELETE SET NULL
);

-- One live planned invoice per key. Superseded rows keep history.
CREATE UNIQUE INDEX IF NOT EXISTS uq_finance_planned_invoices_live_key
  ON finance_planned_invoices (planned_invoice_key)
  WHERE status <> 'superseded';
-- One Xero invoice satisfies at most one live planned invoice.
CREATE UNIQUE INDEX IF NOT EXISTS uq_finance_planned_invoices_xero
  ON finance_planned_invoices (matched_xero_invoice_id)
  WHERE matched_xero_invoice_id IS NOT NULL AND status <> 'superseded';
CREATE INDEX IF NOT EXISTS idx_finance_planned_invoices_month
  ON finance_planned_invoices (billing_month, client_id);

-- Which record (MBA-month) and which lines make up each planned invoice.
CREATE TABLE IF NOT EXISTS finance_planned_invoice_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planned_invoice_id bigint NOT NULL REFERENCES finance_planned_invoices(id) ON DELETE CASCADE,
  finance_billing_record_id bigint NOT NULL REFERENCES finance_billing_records(id) ON DELETE CASCADE,
  -- Media line ids folded into this invoice line; empty for service lines.
  line_item_ids text[] NOT NULL DEFAULT '{}',
  item_code text NOT NULL,
  description text NOT NULL,
  supplier_label text NULL,
  amount_cents bigint NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_finance_planned_invoice_lines_record
  ON finance_planned_invoice_lines (finance_billing_record_id);


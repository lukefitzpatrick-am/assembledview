// Reads lib/pdf/fonts/src/*.ttf and writes lib/pdf/fonts/plusJakartaSans.ts.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const srcDir = join(root, "lib", "pdf", "fonts", "src")
const faces = [
  ["regular", "PlusJakartaSans-Regular.ttf"],
  ["bold", "PlusJakartaSans-Bold.ttf"],
  ["extrabold", "PlusJakartaSans-ExtraBold.ttf"],
]

const exports = faces
  .map(([key, file]) => {
    const b64 = readFileSync(join(srcDir, file)).toString("base64")
    return `export const ${key} =\n  ${JSON.stringify(b64)}`
  })
  .join("\n\n")

const out = `// Generated by scripts/brand/build-pdf-fonts.mjs. Do not edit.
// Regenerate with: node scripts/brand/build-pdf-fonts.mjs

${exports}
`
writeFileSync(join(root, "lib", "pdf", "fonts", "plusJakartaSans.ts"), out)
console.log("wrote lib/pdf/fonts/plusJakartaSans.ts")
